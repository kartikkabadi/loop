#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { basename, dirname, isAbsolute, join, relative, resolve } from "node:path";

const MAX_OUTPUT_CHARS = 24_000;
const AUTHORITY_CANDIDATES = [
  "AGENTS.md",
  "CLAUDE.md",
  "CONTRIBUTING.md",
  "SECURITY.md",
  "VISION.md",
  "LOOP.md",
  "TASKS.md",
  "README.md",
];
const SCRIPT_HINTS = [
  "check",
  "test",
  "test:unit",
  "test:e2e",
  "test:browser",
  "lint",
  "format:check",
  "typecheck",
  "build",
  "verify",
  "preview",
];

function argumentValue(name, fallback) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : (process.argv[index + 1] ?? fallback);
}

function runGit(repo, args) {
  try {
    return execFileSync("git", ["-C", repo, ...args], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "unknown";
  }
}

function redactCommand(command) {
  return command
    .replace(/([A-Z][A-Z0-9_]*(?:TOKEN|KEY|SECRET|PASSWORD|PASS))=[^\s]+/gi, "$1=<redacted>")
    .replace(/(https?:\/\/[^\s]*)(token|key|secret|password)=[^\s&]+/gi, "$1$2=<redacted>");
}

function listExisting(repo, names) {
  return names.filter((name) => existsSync(join(repo, name)));
}

function packageSummary(packageJson) {
  if (!packageJson || typeof packageJson !== "object") return [];
  const lines = [];
  if (typeof packageJson.packageManager === "string")
    lines.push(`- package manager: ${packageJson.packageManager}`);
  if (typeof packageJson.engines?.node === "string")
    lines.push(`- Node.js: ${packageJson.engines.node}`);
  const scripts =
    packageJson.scripts && typeof packageJson.scripts === "object" ? packageJson.scripts : {};
  const names = Object.keys(scripts).filter((name) => SCRIPT_HINTS.includes(name));
  for (const name of names) lines.push(`- ${name}: ${redactCommand(String(scripts[name]))}`);
  return lines;
}

async function readPackageJson(repo) {
  const path = join(repo, "package.json");
  if (!existsSync(path)) return undefined;
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch {
    return undefined;
  }
}

async function buildContext(repo) {
  const packageJson = await readPackageJson(repo);
  const repoName = basename(repo);
  const authorityFiles = listExisting(repo, AUTHORITY_CANDIDATES);
  const supportingFiles = listExisting(repo, [
    "pnpm-lock.yaml",
    "package-lock.json",
    "yarn.lock",
    "bun.lockb",
    "bun.lock",
    ".nvmrc",
    ".node-version",
    "wrangler.toml",
    "wrangler.jsonc",
    "playwright.config.ts",
    "playwright.config.js",
    "vitest.config.ts",
    "vitest.config.js",
  ]);
  const packageLines = packageSummary(packageJson);
  const branch = runGit(repo, ["branch", "--show-current"]);
  const head = runGit(repo, ["rev-parse", "HEAD"]);
  const defaultBranch = runGit(repo, [
    "symbolic-ref",
    "refs/remotes/origin/HEAD",
    "--short",
  ]).replace(/^origin\//, "");
  const status = runGit(repo, ["status", "--short", "--untracked-files=no"]);
  const statusLine = status === "unknown" ? "unknown" : status ? "changes present" : "clean";
  const lines = [
    "# Loop Repository Context",
    "",
    "Generated by `scripts/generate-chatgpt-project-context.mjs`.",
    "This file contains repository shape and safe command metadata only. It does",
    "not contain source files, environment values, credentials, or agent logs.",
    "",
    "## Identity",
    "",
    `- repository directory: ${repoName}`,
    "- repository root: <checkout>",
    `- current branch: ${branch}`,
    `- current head: ${head}`,
    `- default branch: ${defaultBranch}`,
    `- working tree: ${statusLine}`,
    "",
    "## Authority files found",
    "",
    authorityFiles.length ? authorityFiles.map((name) => `- ${name}`).join("\n") : "- none found",
    "",
    "## Supporting files found",
    "",
    supportingFiles.length ? supportingFiles.map((name) => `- ${name}`).join("\n") : "- none found",
    "",
    "## Package and verification hints",
    "",
    packageLines.length ? packageLines.join("\n") : "- no package.json or recognized scripts found",
    "",
    "## Loading rule",
    "",
    "Read the authority files before planning. Treat this generated inventory as",
    "a discovery aid, not as a replacement for the repository instructions.",
    "Confirm the live base SHA, relevant paths, required tools, and visual proof",
    "requirements before creating or dispatching a Loop task.",
    "",
  ];
  const text = lines.join("\n");
  if (text.length > MAX_OUTPUT_CHARS)
    throw new Error("generated repository context exceeds its size limit");
  return text;
}

const requestedRepo = argumentValue("--repo", process.cwd());
const repo = resolve(
  isAbsolute(requestedRepo) ? requestedRepo : join(process.cwd(), requestedRepo),
);
const requestedOutput = argumentValue(
  "--output",
  join(repo, "chatgpt-project", "LOOP-REPO-CONTEXT.md"),
);
const output = resolve(isAbsolute(requestedOutput) ? requestedOutput : join(repo, requestedOutput));
const text = await buildContext(repo);
await mkdir(dirname(output), { recursive: true });
await writeFile(output, text, "utf8");
console.log(`Wrote ${relative(process.cwd(), output) || output}`);
